import { describe, expect, test } from "bun:test"
import { readFile } from "node:fs/promises"
import { join } from "node:path"

import { ConsultationModeSchema } from "../packages/consultation-core/src/enums.ts"

/**
 * Cross-layer mode consistency: the Zod schema, the always-on consultant
 * prompt, and the generated skill must agree on the public mode list and on
 * each mode's output template. Eval-case coverage (`modes` arrays) is asserted
 * alongside the fixtures in a later phase.
 */
const REPO_ROOT = join(import.meta.dir, "..")
const MODES = ["select", "verify", "plan", "research", "guide", "author", "design"] as const

const TEMPLATE_HEADINGS: Record<(typeof MODES)[number], string> = {
  select: "### select: choose and try",
  verify: "### verify: verdict first",
  plan: "### plan: feasibility first",
  research: "### research: bottom line then meaning",
  guide: "### guide: shortest path first",
  author: "### author: delivery brief",
  design: "### design: decision record",
}

async function readAsset(path: string): Promise<string> {
  return readFile(join(REPO_ROOT, path), "utf8")
}

describe("consultation mode consistency", () => {
  test("the schema lists exactly the public modes", () => {
    expect(ConsultationModeSchema.options).toEqual([...MODES])
  })

  test("the consultant prompt names every mode and keeps a design entry", async () => {
    const prompt = await readAsset("assets/agents/consultant.md")

    for (const mode of MODES) expect(prompt).toContain(`\`${mode}\``)
    expect(prompt).toContain("- **design**")
  })

  test("the generated skill names every mode and carries its template", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")

    for (const mode of MODES) {
      expect(skill).toContain(`\`${mode}\``)
      expect(skill).toContain(TEMPLATE_HEADINGS[mode])
    }
  })

  test("the skill carries the design method and record rules", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")

    for (const marker of [
      "## Design Mode",
      "### Method",
      "### The design record",
      "### Anti-patterns (do not)",
      "one-way-door pre-mortem",
      "six-part scenario",
    ]) {
      expect(skill).toContain(marker)
    }
  })

  test("every mode appears in at least one eval case's modes array", async () => {
    const cases = JSON.parse(
      await readAsset("evals/fixtures/consultation-cases.json"),
    ) as Array<{ id: string; modes?: string[] }>
    const covered = new Set(cases.flatMap((entry) => entry.modes ?? []))

    for (const mode of MODES) {
      expect(covered.has(mode)).toBe(true)
    }
    for (const mode of covered) {
      expect(MODES).toContain(mode as (typeof MODES)[number])
    }
  })

  test("the skill's channel policy is collection-first and reports the risk", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")

    expect(skill).toContain("Collect first")
    expect(skill).toContain("host-provided tool")
    expect(skill).toContain("user owns the decision")
    expect(skill).toContain("try every available route")
    expect(skill).toContain("may be collected and used")
    expect(skill).toContain("legal or compliance risk")
    expect(skill).not.toContain("list which channels were used")
    for (const removed of [
      "pirated sources and leaked data are allowed",
      "bypass login and paywalls where possible",
      "The user owns the legal and compliance risk",
    ]) {
      expect(skill).not.toContain(removed)
    }
  })

  test("the installed skill asset is generated from skill-src", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")

    expect(skill.startsWith("---\n")).toBe(true)
    expect(skill).toContain(
      "<!-- generated by script/gen-skill.ts from skill-src/consultation; do not edit -->",
    )
  })
})
