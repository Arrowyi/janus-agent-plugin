import { describe, expect, test } from "bun:test"
import { readFile } from "node:fs/promises"
import { join } from "node:path"

import { ConsultationModeSchema } from "../packages/consultation-core/src/enums.ts"

/**
 * Cross-layer mode consistency: the Zod schema, the always-on consultant
 * prompt, and the generated skill must agree on the public mode list and on
 * each mode's output template. Eval-case coverage (`modes` arrays) is asserted
 * alongside the fixtures in a later phase.
 */
const REPO_ROOT = join(import.meta.dir, "..")
const MODES = ["select", "verify", "plan", "research", "guide", "author", "design"] as const

const TEMPLATE_HEADINGS: Record<(typeof MODES)[number], string> = {
  select: "### select: choose and try",
  verify: "### verify: verdict first",
  plan: "### plan: feasibility first",
  research: "### research: bottom line then meaning",
  guide: "### guide: shortest path first",
  author: "### author: delivery brief",
  design: "### design: decision record",
}

async function readAsset(path: string): Promise<string> {
  return readFile(join(REPO_ROOT, path), "utf8")
}

describe("consultation mode consistency", () => {
  test("the schema lists exactly the public modes", () => {
    expect(ConsultationModeSchema.options).toEqual([...MODES])
  })

  test("the consultant prompt names every mode and points to the shared card", async () => {
    const prompt = await readAsset("assets/agents/consultant.md")

    for (const mode of MODES) expect(prompt).toContain(`\`${mode}\``)
    expect(prompt).toContain("shared Mode Routing card")
    expect(prompt).not.toContain("- **select** —")
  })

  test("the generated skill carries the mode card once, with no marker or role-prompt duplicate", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")
    const fragment = (await readAsset("assets/principles/mode-routing.md")).trim()
    const core = await readAsset("skill-src/consultation/core.md")

    expect(skill).toContain(fragment)
    expect(skill).not.toContain("<!-- MODE-ROUTING -->")
    expect(skill.split("**Mode card** (first match wins)").length - 1).toBe(1)
    expect(core).not.toContain("Route by **ask**, not by sentence")
    for (const role of ["janus", "consultant"]) {
      const prompt = await readAsset(`assets/agents/${role}.md`)
      expect(prompt).not.toContain("Route by **ask**, not by sentence")
    }
  })

  test("the generated skill names every mode and carries its template", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")

    for (const mode of MODES) {
      expect(skill).toContain(`\`${mode}\``)
      expect(skill).toContain(TEMPLATE_HEADINGS[mode])
    }
  })

  test("the skill carries the design method and record rules", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")

    for (const marker of [
      "## Design Mode",
      "### Method",
      "### The design record",
      "### Anti-patterns (do not)",
      "one-way-door pre-mortem",
      "six-part scenario",
    ]) {
      expect(skill).toContain(marker)
    }
  })

  test("every mode appears in at least one eval case's modes array", async () => {
    const cases = JSON.parse(
      await readAsset("evals/fixtures/consultation-cases.json"),
    ) as Array<{ id: string; modes?: string[] }>
    const covered = new Set(cases.flatMap((entry) => entry.modes ?? []))

    for (const mode of MODES) {
      expect(covered.has(mode)).toBe(true)
    }
    for (const mode of covered) {
      expect(MODES).toContain(mode as (typeof MODES)[number])
    }
  })

  test("the skill's channel policy is collection-first and reports the risk", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")

    expect(skill).toContain("Collect first")
    expect(skill).toContain("host-provided tool")
    expect(skill).toContain("user owns the decision")
    expect(skill).toContain("try every available route")
    expect(skill).toContain("may be collected and used")
    expect(skill).toContain("legal or compliance risk")
    expect(skill).not.toContain("list which channels were used")
    for (const removed of [
      "pirated sources and leaked data are allowed",
      "bypass login and paywalls where possible",
      "The user owns the legal and compliance risk",
    ]) {
      expect(skill).not.toContain(removed)
    }
  })

  test("the installed skill asset is generated from skill-src", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")

    expect(skill.startsWith("---\n")).toBe(true)
    expect(skill).toContain(
      "<!-- generated by script/gen-skill.ts from skill-src/consultation; do not edit -->",
    )
  })

  test("the workflow carries the value-of-information stop rule", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")

    expect(skill).toContain("value-of-information")
    expect(skill).toContain("cannot change the decision")
    expect(skill).toContain("cheap and reversible")
    expect(skill).toContain("irreversible or expensive")
    expect(skill).toContain("停止理由：...；未查：...")
  })

  test("the plan template places the pre-mortem block between constraints and steps", async () => {
    const skill = await readAsset("assets/skills/consultation/SKILL.md")
    const constraints = skill.indexOf("可行性与约束：")
    const failureModes = skill.indexOf("失败模式与早期信号")
    const steps = skill.indexOf("步骤：")

    expect(failureModes).toBeGreaterThan(-1)
    expect(failureModes).toBeGreaterThan(constraints)
    expect(failureModes).toBeLessThan(steps)
    expect(skill).toContain("observable early signal")
  })

  test("the claim-type table is generated from the single shared fragment", async () => {
    const fragment = (await readAsset("assets/principles/claim-types.md")).trim()
    const skill = await readAsset("assets/skills/consultation/SKILL.md")
    const analyst = await readAsset("assets/agents/analyst.md")
    const header = "| Claim type | Verification method |"

    expect(skill).toContain(fragment)
    expect(skill).not.toContain("<!-- CLAIM-TYPES -->")
    expect(skill.split(header).length - 1).toBe(1)
    expect(analyst).toContain("Claim Types")
    expect(analyst).not.toContain(header)
  })

  test("the shared source criteria fragment is the single source of the seven criteria", async () => {
    const fragment = (await readAsset("assets/principles/source-criteria.md")).trim()
    const skill = await readAsset("assets/skills/consultation/SKILL.md")
    const criteria = [
      /primary versus secondary/,
      /expertise or legal accountability/,
      /transparent and reproducible method/,
      /independence and original provenance/,
      /commercial or ideological conflicts/,
      /recency, region, and applicability/,
      /independent support or contradiction/,
    ]

    for (const criterion of criteria) expect(fragment).toMatch(criterion)
    expect(skill).toContain(fragment)
    expect(skill.split(fragment).length - 1).toBe(1)
    expect(skill).not.toContain("<!-- SOURCE-CRITERIA -->")

    for (const file of ["assets/agents/explorer.md", "assets/agents/consultation-critic.md"]) {
      const text = await readAsset(file)
      expect(text).toContain("shared Source Criteria")
      // The inline enumeration must live in the fragment, not the role asset.
      for (const inlineCriterion of [
        "primary versus secondary status",
        "expertise or legal accountability",
        "independent support or contradiction",
      ]) {
        expect(text).not.toContain(inlineCriterion)
      }
      for (const grade of ["high", "medium", "low", "lead_only"]) expect(text).toContain(grade)
    }
  })

  test("the consultant prompt and the skill agree on role triggers", async () => {
    const consultant = await readAsset("assets/agents/consultant.md")
    const skill = await readAsset("assets/skills/consultation/SKILL.md")

    for (const role of ["explorer", "analyst", "critic", "verifier", "writer", "lite", "coder"]) {
      expect(consultant).toContain(`\`${role}\``)
      expect(skill).toContain(`\`${role}\``)
    }
    expect(consultant).toContain(
      "Dispatch by default when the work falls within a specialist's dedicated profile",
    )
    expect(skill).toContain("Dispatch by default when the work falls within a specialist's profile")
    // Single-copy lock: the full trigger table exists only in the skill.
    expect(skill.split("Dispatch when this concrete check applies").length - 1).toBe(1)
    expect(consultant).not.toContain("Dispatch when this concrete check applies")
  })

  test("the consultant prompt and the skill agree on the channel policy", async () => {
    const consultant = await readAsset("assets/agents/consultant.md")
    const skill = await readAsset("assets/skills/consultation/SKILL.md")
    const fragment = (await readAsset("assets/principles/channel-policy.md")).trim()

    expect(fragment).toContain("| T0 public |")
    expect(fragment).toContain("| T3 gated deep web |")
    expect(fragment).toContain("host-provided tool")
    expect(skill).toContain(fragment)
    expect(skill.split(fragment).length - 1).toBe(1)
    expect(skill).not.toContain("<!-- CHANNEL-POLICY -->")

    expect(consultant).toContain("shared channel ladder (Channel Policy)")
    expect(consultant).not.toMatch(/\bT[0-3]\b/)
    for (const phrase of [
      "Collect first",
      "host-provided tool",
      "user owns the decision",
      "try every available route",
      "may be collected and used",
      "legal or compliance risk",
      "Never ask for passwords, session cookies, or API keys",
    ]) {
      expect(consultant).toContain(phrase)
      expect(skill).toContain(phrase)
    }
    for (const removed of ["bypass login and paywalls", "The user owns the legal and compliance risk"]) {
      expect(consultant).not.toContain(removed)
      expect(skill).not.toContain(removed)
    }
  })
})
