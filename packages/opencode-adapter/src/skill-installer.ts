import { mkdir, readFile, readdir, rename, rm, writeFile } from "node:fs/promises"
import { existsSync } from "node:fs"
import { join } from "node:path"
import { resolveAsset } from "./asset-paths.ts"

const USER_MODIFIED_MARKER = "<!-- user-modified -->"

export const CONSULTATION_SKILLS = [
  "consultation",
  "consultation-design",
  "consultation-doc",
] as const

/**
 * Resolve the opencode config directory from environment variables.
 *
 * Priority: `$OPENCODE_CONFIG_DIR` >
 * `$XDG_CONFIG_HOME/opencode` >
 * `~/.config/opencode`.
 */
export function resolveOpencodeConfigDir(env: NodeJS.ProcessEnv): string {
  if (env.OPENCODE_CONFIG_DIR && env.OPENCODE_CONFIG_DIR.length > 0) {
    return env.OPENCODE_CONFIG_DIR
  }
  const xdg = env.XDG_CONFIG_HOME
  if (xdg && xdg.length > 0) {
    return join(xdg, "opencode")
  }
  const home = env.HOME ?? ""
  return join(home, ".config", "opencode")
}

/**
 * Install the `consultation` skill into the opencode config directory.
 *
 * The skill file is written to `<configDir>/skills/consultation/SKILL.md`
 * from the repo-root `assets/skills/consultation/SKILL.md`. The file is
 * written only when missing or when the content differs from the asset.
 * A file whose first line is `<!-- user-modified -->` is never overwritten.
 * Writes are atomic (write tmp then rename).
 */
async function installSkill(env: NodeJS.ProcessEnv, skillName: string): Promise<void> {
  const configDir = resolveOpencodeConfigDir(env)
  const targetDir = join(configDir, "skills", skillName)
  const targetFile = join(targetDir, "SKILL.md")

  const assetPath = resolveAsset(`skills/${skillName}/SKILL.md`)
  const assetContent = await readFile(assetPath, "utf8")

  let existing: string | undefined
  try {
    existing = await readFile(targetFile, "utf8")
  } catch {
    // missing file — proceed to write
  }

  if (existing !== undefined) {
    if (existing.startsWith(USER_MODIFIED_MARKER)) return
    if (existing === assetContent) return
  }

  await mkdir(targetDir, { recursive: true })
  const tmpFile = `${targetFile}.tmp`
  await writeFile(tmpFile, assetContent, "utf8")
  await rename(tmpFile, targetFile)
}

/**
 * Fingerprint of a skill generated by this repo's `script/gen-skill.ts`: the
 * emitted marker prefix plus the product name. The fingerprint — never a
 * hardcoded list of retired skill names — decides which staged skills a
 * startup install may prune.
 */
const GENERATED_MARKER_PREFIX = "<!-- generated by script/gen-skill.ts from skill-src/"
const PRODUCT_NAME = "janus-agent"

/**
 * Remove retired Janus-generated skill directories left by earlier installs.
 *
 * A staged skill directory is pruned only when its SKILL.md was generated by
 * this repo (carries the gen-skill marker and the product name) and was not
 * marked user-modified. User-modified and foreign skills are kept untouched,
 * and a directory that still holds other files after the SKILL.md removal is
 * kept. Retired skill names are never hardcoded: the fingerprint is the only
 * matcher. All errors are ignored — pruning is best-effort cleanup.
 */
async function pruneRetiredSkills(env: NodeJS.ProcessEnv): Promise<void> {
  const skillsDir = join(resolveOpencodeConfigDir(env), "skills")
  let names: string[]
  try {
    names = await readdir(skillsDir)
  } catch {
    return
  }
  for (const name of names) {
    if ((CONSULTATION_SKILLS as readonly string[]).includes(name)) continue
    const dir = join(skillsDir, name)
    let content: string
    try {
      content = await readFile(join(dir, "SKILL.md"), "utf8")
    } catch {
      continue
    }
    if (content.startsWith(USER_MODIFIED_MARKER)) continue
    if (!content.includes(GENERATED_MARKER_PREFIX)) continue
    if (!content.includes(PRODUCT_NAME)) continue
    try {
      await rm(join(dir, "SKILL.md"))
      const rest = await readdir(dir)
      if (rest.length === 0) await rm(dir, { recursive: true })
    } catch {
      // non-fatal
    }
  }
}

/** Install the three consultation skills and prune retired generated skills. */
export async function installConsultationSkills(env: NodeJS.ProcessEnv): Promise<void> {
  for (const skillName of CONSULTATION_SKILLS) await installSkill(env, skillName)
  await pruneRetiredSkills(env)
}
