import { mkdir, readdir, readFile, rename, unlink, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { resolveAsset } from "./asset-paths.ts"
import { resolveOpencodeConfigDir } from "./skill-installer.ts"

/**
 * The unified prefix for the memory-browse slash command, matching the CLI
 * binary and the MCP server name so all three surfaces share one name.
 */
export const MEMORY_COMMAND_PREFIX = "janus-memory"

/**
 * The model inventory/evaluation/switch command. It is explicit-only: no
 * skill is installed and nothing is triggered implicitly.
 */
export const MODELS_COMMAND_PREFIX = "janus-models"

/**
 * The guided plugin-config command: list, view, set, clear, reset, and
 * validate `config.jsonc` through the `janus_config` tool.
 */
export const CONFIG_COMMAND_PREFIX = "janus-config"

const USER_MODIFIED_MARKER = "<!-- user-modified -->"

/**
 * The data-root fingerprint that identifies a command file as generated by
 * this plugin: retired Janus commands reference paths under the Janus data
 * root, while a user's own command files do not.
 */
const DATA_ROOT_FINGERPRINT = "$XDG_DATA_HOME/janus-agent/"

/**
 * Every command file this plugin currently installs, used to decide which
 * previously installed commands are retired orphans during pruning.
 */
export const INSTALLED_COMMAND_PREFIXES = [
  MEMORY_COMMAND_PREFIX,
  MODELS_COMMAND_PREFIX,
  CONFIG_COMMAND_PREFIX,
] as const

function commandContent(): string {
  return `---
description: Browse and manage your saved consultations — list them, view one, or delete/forget one or many at once.
---

Help the user browse and manage their saved consultations using the janus-memory MCP tools (memory_recall / memory_expand / memory_manage). Do NOT run the janus-memory CLI here: the MCP tools already own this workflow.

1. List them: call \`memory_recall\` with \`tier: "standard"\`, \`limit: 50\`, and \`expandTop: 50\` so each consultation's current conclusion is included. Present the result as a numbered list, ONE line per consultation — the question summary (title), a short conclusion, and the date. Keep it compact. If it is empty, say there are no saved consultations yet and suggest asking the consultant a question first.

2. Then show exactly this operation hint:

操作提示：
- 查看详情：回复序号（如 "1"）
- 删除（可恢复）：回复 "删 2"，或批量 "删 2，4，5"、"删 4~9"
- 永久删除：回复 "忘 …"（同样支持单个、多个、区间）
- 只保留：回复 "留 5，7"（删除其余全部，可恢复）

3. Map each number to that entry's \`itemId\`. Parse the user's reply into target positions:
   - a bare number N → VIEW only: call \`memory_expand\` with \`itemIds: ["<itemId of #N>"]\` and \`level: 3\`, then present the full consultation (question, conclusion, confidence, stability, key sources). No confirmation needed.
   - otherwise it is a delete/forget/keep command. Resolve the position set:
     - single: "2" → {2}
     - list: "2，4，5" (accept "," "、" and spaces) → {2,4,5}
     - range: "4~9", "4-9", "4 到 9" → every integer from 4 to 9 inclusive
     - keep-only ("留" / "只保留" N…): the targets are ALL positions EXCEPT the listed ones
     - a mix like "2，4~6，8" is allowed — union all the parts
   Map every resolved position to its \`itemId\`. "删" and "留" mean \`action: "retire"\`; "忘" means \`action: "forget"\`.

4. For any delete/forget/keep command (especially a batch), FIRST show the user exactly which consultations will be affected (their numbers and titles) plus the total count, and ask them to confirm. Only after they confirm, call \`memory_manage\` once per target \`itemId\`, then report the result (e.g., "已删除 5 条：<titles>"). If a position is out of range, say so and do nothing until they give valid ones.

This lists consultations for the current project (memory is per-project). For a cross-project global list, run the janus-memory CLI when OpenCode is not running.
`
}

async function installCommandFile(
  configDir: string,
  commandName: string,
  content: string,
): Promise<void> {
  const targetDir = join(configDir, "commands")
  const targetFile = join(targetDir, `${commandName}.md`)

  let existing: string | undefined
  try {
    existing = await readFile(targetFile, "utf8")
  } catch {
    // missing file — proceed to write
  }
  if (existing !== undefined) {
    if (existing.startsWith(USER_MODIFIED_MARKER)) return
    if (existing === content) return
  }

  await mkdir(targetDir, { recursive: true })
  const tmpFile = `${targetFile}.tmp`
  await writeFile(tmpFile, content, "utf8")
  await rename(tmpFile, targetFile)
}

/**
 * Install the memory-browse slash command into the opencode config directory.
 * Writes `<configDir>/commands/janus-memory.md`. Written only when missing or
 * when the content differs; a file whose first line is `<!-- user-modified -->`
 * is never overwritten.
 */
export async function installMemoryCommands(env: NodeJS.ProcessEnv): Promise<void> {
  const configDir = resolveOpencodeConfigDir(env)
  await installCommandFile(configDir, MEMORY_COMMAND_PREFIX, commandContent())
}

/**
 * Install the explicit `/janus-models` command from the shipped asset. The
 * asset is the single source of truth; the file is written only when missing
 * or when the content differs, and a user-modified file is never overwritten.
 */
export async function installModelsCommand(env: NodeJS.ProcessEnv): Promise<void> {
  const configDir = resolveOpencodeConfigDir(env)
  const content = await readFile(resolveAsset("commands/janus-models.md"), "utf8")
  await installCommandFile(configDir, MODELS_COMMAND_PREFIX, content)
}

/**
 * Install the explicit `/janus-config` command from the shipped asset. The
 * asset is the single source of truth; the file is written only when missing
 * or when the content differs, and a user-modified file is never overwritten.
 */
export async function installConfigCommand(env: NodeJS.ProcessEnv): Promise<void> {
  const configDir = resolveOpencodeConfigDir(env)
  const content = await readFile(resolveAsset("commands/janus-config.md"), "utf8")
  await installCommandFile(configDir, CONFIG_COMMAND_PREFIX, content)
}

const RETIRED_COMMAND_FILE = /^janus-[a-z0-9-]+\.md$/

/**
 * Remove previously installed Janus command files whose command no longer
 * ships. Scans `<configDir>/commands` for `janus-*.md` files whose stem is
 * not in `INSTALLED_COMMAND_PREFIXES` and deletes only files that are both
 * not user-modified and fingerprint-bearing (they reference the Janus data
 * root), so user-modified, foreign, and non-janus files are never touched.
 * Missing directories and per-file errors are ignored non-fatally.
 */
export async function pruneRetiredCommands(env: NodeJS.ProcessEnv): Promise<void> {
  const commandsDir = join(resolveOpencodeConfigDir(env), "commands")
  let entries: string[]
  try {
    entries = await readdir(commandsDir)
  } catch {
    return
  }
  const installedStems = new Set<string>(INSTALLED_COMMAND_PREFIXES)
  for (const entry of entries) {
    if (!RETIRED_COMMAND_FILE.test(entry)) continue
    if (installedStems.has(entry.replace(/\.md$/, ""))) continue
    const file = join(commandsDir, entry)
    let content: string
    try {
      content = await readFile(file, "utf8")
    } catch {
      continue
    }
    if (content.startsWith(USER_MODIFIED_MARKER)) continue
    if (!content.includes(DATA_ROOT_FINGERPRINT)) continue
    try {
      await unlink(file)
    } catch {
      // leave the file in place rather than failing startup
    }
  }
}
